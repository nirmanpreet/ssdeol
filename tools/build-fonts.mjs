/**
 * FONT PIPELINE — run with:  npm run build:fonts
 * Pulls the latin subsets of Barlow Condensed + Inter from Google Fonts once and
 * writes them into  assets/fonts/  with a local  fonts.css.
 *
 * Why bother? A Google Fonts <link> costs a render-blocking third-party request
 * on every page load. Self-hosting + font-display:swap + a <preload> on the one
 * critical face protects the Lighthouse performance score.
 */
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'assets/fonts');
mkdirSync(OUT, { recursive: true });

// A desktop Chrome UA makes Google serve woff2 instead of ttf.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';
const SRC = 'https://fonts.googleapis.com/css2?family=Barlow+Condensed:wght@700&family=Inter:wght@400..600&display=swap';

const res = await fetch(SRC, { headers: { 'User-Agent': UA } });
if (!res.ok) throw new Error(`Google Fonts returned ${res.status}`);
const css = await res.text();

// Each @font-face is preceded by a /* subset */ comment from Google's API.
const blocks = css.split('/*').slice(1);
const wanted = new Map(); // url -> record (same file can cover several weights)

for (const b of blocks) {
  const subset = b.slice(0, b.indexOf('*/')).trim();          // e.g. "latin"
  if (subset !== 'latin' && subset !== 'latin-ext') continue;
  const family = /font-family:\s*'([^']+)'/.exec(b)?.[1] ?? 'font';
  const weightRaw = /font-weight:\s*([\d ]+)/.exec(b)?.[1]?.trim() ?? '400';
  const url = /url\((https:[^)]+\.woff2)\)/.exec(b)?.[1];
  const range = /unicode-range:\s*([^;]+);/.exec(b)?.[1]?.trim() ?? '';
  if (!url) continue;

  const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${weightRaw.replace(/\s+/g, '-')}-${subset}.woff2`;
  const prev = wanted.get(url);
  if (prev) {
    // Google served ONE variable file covering several weights — widen the
    // declared range instead of overwriting (this is what silently killed 400).
    prev.weight = weightRaw.includes(' ') ? weightRaw : prev.weight;
    if (weightRaw.includes(' ') && !prev.weight.includes(' ')) prev.weight = weightRaw;
  }
  wanted.set(url, { file, family, weight: weightRaw, subset, range, url });
}

let out = `/* Self-hosted webfonts — generated by tools/build-fonts.mjs. Do not edit by hand.
   Source: Google Fonts (Barlow Condensed + Inter), SIL Open Font License 1.1.
   Only the latin + latin-ext subsets are bundled, which is all an en-AU site needs.
   Self-hosted so there is no render-blocking third-party request on first paint. */\n\n`;

for (const { file, family, weight, subset, range, url } of wanted.values()) {
  const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
  writeFileSync(resolve(OUT, file), buf);
  out += `@font-face {\n  font-family: '${family}';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  /* RELATIVE url — resolves against this stylesheet's own location\n     (/assets/fonts/), so the font works under any base path: github.io/<repo>/,\n     a custom domain, or a subfolder. An absolute /assets/... here would 404\n     the moment the site moved. */\n  src: url('./${file}') format('woff2');\n  unicode-range: ${range};\n}\n\n`;
  console.log(`  ${file.padEnd(34)} ${(buf.length / 1024).toFixed(1)} KB`);
}

writeFileSync(resolve(OUT, 'fonts.css'), out);
const total = [...wanted.values()].reduce((n, w) => n + w.file.length, 0);
console.log(`\n  ${wanted.size} files -> assets/fonts/fonts.css`);
console.log(`  total on the critical path: ~${[...wanted].filter(([, v]) => v.subset === 'latin').length} latin faces\n`);